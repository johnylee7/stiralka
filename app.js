const TRANSLATIONS = {
  ru: RU_TRANSLATION,
  kz: KZ_TRANSLATION,
};

function setMeta(selector, value) {
  const meta = document.querySelector(selector);
  if (meta) {
    meta.setAttribute("content", value);
  }
}

function setSectionHeading(root, data) {
  if (!root) {
    return;
  }
  const paragraphs = root.querySelectorAll("p");
  if (paragraphs[0]) {
    paragraphs[0].textContent = data.eyebrow;
  }
  const title = root.querySelector("h2");
  if (title) {
    title.textContent = data.title;
  }
  if (paragraphs[1]) {
    paragraphs[1].textContent = data.text;
  }
}

function setListHTML(elements, values) {
  elements.forEach((element, index) => {
    if (values[index] !== undefined) {
      element.innerHTML = values[index];
    }
  });
}

function setListText(elements, values) {
  elements.forEach((element, index) => {
    if (values[index] !== undefined) {
      element.textContent = values[index];
    }
  });
}

function createLogoTile(name) {
  return `
    <div class="logo-tile" aria-label="${name}" title="${name}">
      <div class="logo-mark">${BRAND_LOGOS[name] || `<span>${name}</span>`}</div>
    </div>`;
}

function renderLogos() {
  serviceLogoRoots.forEach((root) => {
    const setName = root.dataset.logoSet;
    const brands = LOGO_SETS[setName] || [];
    root.innerHTML = brands.map((brand) => createLogoTile(brand)).join("");
  });

  if (brandLogosRoot) {
    brandLogosRoot.innerHTML = LOGO_SETS.all.map((brand) => createLogoTile(brand)).join("");
  }
}

function renderSchemas(language) {
  const t = TRANSLATIONS[language];
  const schemaScripts = document.querySelectorAll('script[type="application/ld+json"]');
  const applianceSchema = {
    "@context": "https://schema.org",
    "@type": "ApplianceRepair",
    name: "ALMAFIX Home Service",
    telephone: PHONE,
    priceRange: "₸₸",
    address: {
      "@type": "PostalAddress",
      addressLocality: "Алматы",
      addressRegion: t.schema.addressRegion,
      addressCountry: "KZ",
    },
    areaServed: [
      { "@type": "City", name: "Алматы" },
      { "@type": "AdministrativeArea", name: t.schema.addressRegion },
    ],
    openingHours: ["Mo-Su 08:00-22:00"],
    serviceType: t.schema.serviceType,
    hasOfferCatalog: {
      "@type": "OfferCatalog",
      name: t.schema.catalogName,
      itemListElement: t.schema.catalogItems.map((item) => ({
        "@type": "Offer",
        itemOffered: {
          "@type": "Service",
          name: item,
        },
      })),
    },
  };
  const faqSchema = {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity: t.faq.items.map((item) => ({
      "@type": "Question",
      name: item.q,
      acceptedAnswer: {
        "@type": "Answer",
        text: item.a,
      },
    })),
  };

  if (schemaScripts[0]) {
    schemaScripts[0].textContent = JSON.stringify(applianceSchema, null, 2);
  }
  if (schemaScripts[1]) {
    schemaScripts[1].textContent = JSON.stringify(faqSchema, null, 2);
  }
}

